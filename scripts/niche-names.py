"""
Draws the big niche names (Home header, Discover niche pages) as vector shapes.

Why: on iPhone, live text in these script fonts got its letters sliced at the
edges (the o, g, h, y and t reach past their own slots) and the joins broke,
whatever padding we tried (founder's screenshots, Nov 27 2026). Shapes copied
straight from the two font files can't be clipped, and each join can be placed
by hand.

Run after adding a niche or changing a join (SPECS below):
  pip install fonttools uharfbuzz
  python3 scripts/niche-names.py
It writes src/lib/niche-name-paths.ts.
"""
import json, os
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GV = os.path.join(ROOT, 'node_modules/@expo-google-fonts/great-vibes/400Regular/GreatVibes_400Regular.ttf')
HVM = os.path.join(ROOT, 'node_modules/@expo-google-fonts/herr-von-muellerhoff/400Regular/HerrVonMuellerhoff_400Regular.ttf')
# A sister font of Herr Von Muellerhoff (same designer, same hairline slant), used only for the r in
# Photography: Herr's r looked messy and the founder wanted a cleaner script r (Nov 27 2026). OFL; only its
# outline is copied here, the app never loads it.
MLD = os.path.join(ROOT, 'scripts/fonts/MonsieurLaDoulaise_400Regular.ttf')
CAP_SCALE = 1.45

NICHES = ['Cooking', 'Art', 'Photography', 'Gym', 'Gardening']
# Each name is a row of pieces: (letters, font, size as a share of the name size, gap before it).
# The gap is a share of the name size; negative tucks the piece into the one before so the strokes meet.
# Tuned by eye with the founder (Nov 27 2026).
SPECS = {
    # The C's tail runs into the first o.
    'Cooking': [('C', 'gv', CAP_SCALE, 0), ('ooking', 'hvm', 1, 0.04)],
    # Herr's "rt" read as "Ari", so Art is all Great Vibes; the rt is a little larger so the A's exit flick meets the r.
    'Art': [('A', 'gv', CAP_SCALE, 0), ('rt', 'gv', 1.15, 0.05)],
    # The h starts at the P; a cleaner r from Monsieur La Doulaise.
    'Photography': [('P', 'gv', CAP_SCALE, 0), ('hotog', 'hvm', 1, -0.2), ('r', 'mld', 1.25, -0.06), ('aphy', 'hvm', 1, -0.06)],
}

def spec(base):
    return SPECS.get(base, [(base[0], 'gv', CAP_SCALE, 0), (base[1:], 'hvm', 1, -0.06)])

class Face:
    def __init__(self, path):
        self.tt = TTFont(path)
        self.upm = self.tt['head'].unitsPerEm
        self.glyphs = self.tt.getGlyphSet()
        blob = hb.Blob.from_file_path(path)
        self.hb = hb.Font(hb.Face(blob))
    def shape(self, text):
        buf = hb.Buffer(); buf.add_str(text); buf.guess_segment_properties()
        hb.shape(self.hb, buf, {'kern': True, 'liga': True, 'calt': True})
        order = self.tt.getGlyphOrder()
        x = 0; out = []
        for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
            out.append((order[info.codepoint], x + pos.x_offset, pos.y_offset))
            x += pos.x_advance
        return out, x

def draw(face, shaped, scale, dx, pen_out, bounds):
    # Font units (y up) → ems of the rest's size (y down), shifted by dx.
    for name, gx, gy in shaped:
        s = scale / face.upm
        t = (s, 0, 0, -s, dx + gx * s, -gy * s)
        face.glyphs[name].draw(TransformPen(pen_out, t))
        face.glyphs[name].draw(TransformPen(bounds, t))

def build(faces, label, base):
    pieces = list(spec(base))
    if label != base:
        # "Cooking shop": the extra words continue in the last piece's font at the name size.
        text, font, scale, gap = pieces[-1]
        pieces.append((label[len(base):], font, 1, 0))
    pen = SVGPathPen(None, ntos=lambda v: ('%.4f' % v).rstrip('0').rstrip('.'))
    bounds = BoundsPen(None)
    x = 0
    for text, font, scale, gap in pieces:
        face = faces[font]
        x += gap
        shaped, adv = face.shape(text)
        draw(face, shaped, scale, x, pen, bounds)
        x += adv / face.upm * scale
    x0, y0, x1, y1 = bounds.bounds
    return {'d': pen.getCommands(), 'x': round(x0, 4), 'y': round(y0, 4), 'w': round(x1 - x0, 4), 'h': round(y1 - y0, 4)}

def main():
    faces = {'gv': Face(GV), 'hvm': Face(HVM), 'mld': Face(MLD)}
    names = {}
    for base in NICHES:
        for label in (base, f'{base} shop'):
            names[label] = build(faces, label, base)
    out = os.path.join(ROOT, 'src/lib/niche-name-paths.ts')
    with open(out, 'w') as f:
        f.write('// Generated by scripts/niche-names.py from the Great Vibes and Herr Von Muellerhoff font files. Do not edit by hand.\n')
        f.write('// Each name is one vector outline in ems of the name size: x/y/w/h are its bounds (baseline at y = 0).\n')
        f.write('export type NamePath = { d: string; x: number; y: number; w: number; h: number };\n\n')
        f.write('export const NICHE_NAME_PATHS: Record<string, NamePath> = ' + json.dumps(names, indent=1) + ';\n')
    print('wrote', out, {k: (v['w'], v['h']) for k, v in names.items()})

if __name__ == "__main__":
    main()
